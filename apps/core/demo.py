"""Offline demo of the provider contract, using the scripted fake provider.

    make demo        (or: uv run python -m apps.core.demo)

Needs no API keys and no network, and loads no embedding model. Every model
"reply" below is a fixed string from SCRIPT; the output is synthetic and is not
evaluation evidence. What it shows:
- a structured tool call, a tool result sent back, and a final answer,
- a rate-limit error retried by our own retry loop,
- one trace ID linking the run file and the local trace file.
"""

from __future__ import annotations

import argparse
from datetime import UTC, datetime
from pathlib import Path

from apps.core.cache import CachePolicy
from apps.core.client import ModelClient
from apps.core.errors import ProviderRateLimitError
from apps.core.evidence import (
    CallRecord,
    RunFile,
    RunManifest,
    git_state,
    new_run_id,
    write_run_file,
)
from apps.core.models import REPO_ROOT, ModelRegistry
from apps.core.providers.fake import FakeBackend, ScriptedReply, Step
from apps.core.tracing.base import TraceAttributes
from apps.core.tracing.local import RecordingTracer
from apps.core.types import CompletionRequest, Message, ToolCall, ToolResult, ToolSpec, Usage

BANNER = "SYNTHETIC DEMO - scripted fake provider. Not model output; not evaluation evidence."
PROMPT_VERSION = "demo-v1"

SEARCH_TOOL = ToolSpec(
    name="search_documents",
    description="Search the document corpus (stubbed in this demo).",
    input_schema={
        "type": "object",
        "properties": {"query": {"type": "string"}},
        "required": ["query"],
        "additionalProperties": False,
    },
)

SCRIPT: list[Step] = [
    ProviderRateLimitError(
        "HTTP 429 (scripted)", provider="fake", status_code=429, retry_after_s=0.0
    ),
    ScriptedReply.tool_calls(
        ToolCall(id="call_1", name="search_documents", arguments={"query": "audit trail"}),
        usage=Usage(input_tokens=42, output_tokens=12),
    ),
    ScriptedReply.text(
        "[SCRIPTED FAKE REPLY] This sentence was written into the demo script. "
        "It was not generated by a model.",
        usage=Usage(input_tokens=80, output_tokens=20),
    ),
]


def run_demo(out_dir: Path) -> RunFile:
    run_id = new_run_id()
    run_dir = out_dir / run_id
    registry = ModelRegistry.load()
    tracer = RecordingTracer(path=run_dir / "trace.jsonl")
    backend = FakeBackend(SCRIPT)
    client = ModelClient(
        registry=registry, backends={"fake": backend}, tracer=tracer, sleep=lambda _: None
    )

    calls: list[CallRecord] = []
    history = [Message.user("Which tool would you use to find audit-trail requirements?")]
    with tracer.observe(
        "demo.conversation",
        input={"question": history[0].content[0].model_dump()},
        attributes=TraceAttributes(prompt_version=PROMPT_VERSION, run_id=run_id, tags=("demo",)),
    ) as root:
        for turn in range(2):
            request = CompletionRequest(
                model="fake",
                system="You are a demo assistant.",
                messages=tuple(history),
                tools=(SEARCH_TOOL,),
                max_tokens=256,
            )
            response = client.complete(request)
            calls.append(
                CallRecord(
                    call_id=f"turn-{turn + 1}",
                    trace_id=root.trace_id,
                    request=request,
                    response=response,
                )
            )
            history.append(response.as_assistant_message())
            if not response.tool_calls:
                break
            results = [
                ToolResult(tool_call_id=call.id, content="[stub tool output for the demo]")
                for call in response.tool_calls
            ]
            history.append(Message.tool_results(results))
        root.update(output={"final_text": calls[-1].response.text if calls[-1].response else None})
    tracer.flush()

    sha, dirty = git_state()
    run = RunFile(
        manifest=RunManifest(
            run_id=run_id,
            kind="demo",
            synthetic=True,
            created_at=datetime.now(UTC),
            git_sha=sha,
            git_dirty=dirty,
            models_config_sha256=registry.source_sha256,
            pricing_checked=registry.pricing_checked,
            tracing_backend=tracer.backend,
            cache_policy=CachePolicy.BYPASS,
            prompt_version=PROMPT_VERSION,
            notes=BANNER,
        ),
        calls=calls,
    )
    write_run_file(run_dir / "run.json", run)
    return run


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "runs" / "demo")
    args = parser.parse_args()
    run = run_demo(args.out)
    run_dir = args.out / run.manifest.run_id
    print(BANNER)
    print(f"run id:   {run.manifest.run_id}")
    print(f"trace id: {run.calls[0].trace_id}")
    for call in run.calls:
        if call.response is None:
            continue
        r = call.response
        tools = ", ".join(f"{t.name}({t.arguments})" for t in r.tool_calls) or "-"
        print(
            f"  {call.call_id}: stop_reason={r.stop_reason} attempts={r.execution.attempts} "
            f"tool_calls={tools} tokens(in/out, scripted)={r.generation.usage.input_tokens}/"
            f"{r.generation.usage.output_tokens}"
        )
    print(f"final text: {run.calls[-1].response.text if run.calls[-1].response else None}")
    print(f"run file:   {run_dir / 'run.json'}")
    print(f"trace file: {run_dir / 'trace.jsonl'}")


if __name__ == "__main__":
    main()
